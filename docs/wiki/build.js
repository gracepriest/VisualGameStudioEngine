#!/usr/bin/env node
/* Bundles docs/wiki/content/<id>.md + nav.json into wiki-content.js.
   Run after editing any page:  node docs/wiki/build.js            */
'use strict';
var fs = require('fs');
var path = require('path');

var root = __dirname;
var nav = JSON.parse(fs.readFileSync(path.join(root, 'nav.json'), 'utf8'));
var pages = [];

nav.groups.forEach(function (g) {
  g.pages.forEach(function (id) {
    var file = path.join(root, 'content', id + '.md');
    var raw = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    var split = raw.indexOf('\n---\n');
    if (split === -1) throw new Error(id + '.md: missing "---" front-matter separator');
    var meta = {};
    raw.slice(0, split).split('\n').forEach(function (line) {
      var k = line.indexOf(':');
      if (k > 0) meta[line.slice(0, k).trim()] = line.slice(k + 1).trim();
    });
    if (!meta.title) throw new Error(id + '.md: missing title');
    pages.push({ id: id, title: meta.title, lede: meta.lede || '', body: raw.slice(split + 5).trim() });
  });
});

var out =
  '/* GENERATED by docs/wiki/build.js — edit docs/wiki/content/*.md instead. */\n' +
  'window.WIKI = {\n' +
  '  groups: ' + JSON.stringify(nav.groups, null, 2).split('\n').join('\n  ') + ',\n' +
  '  pages: ' + JSON.stringify(pages, null, 2).split('\n').join('\n  ') + '\n' +
  '};\n';

fs.writeFileSync(path.join(root, 'wiki-content.js'), out);
console.log('wiki-content.js: ' + pages.length + ' pages, ' + (out.length / 1024).toFixed(1) + ' KB');
